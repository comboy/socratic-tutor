// Prepared visuals: drawings and animations made ahead of the lesson, so that when the moment
// comes the tutor drops one in with a line instead of composing a drawing in 20 seconds.
//
//   topics/<slug>/visuals/<name>.js    one visual: a header comment + the body of
//                                      function (el, ctx, d3, opts, kit)   (web/viz/visual.js runs it)
//   topics/<slug>/visuals/_kit.js      the topic's drawing kit: how its recurring things are drawn
//   topics/<slug>/visuals/STYLE.md     the conventions in words ("## In short" is printed by resume)
//   topics/<slug>/visuals/requests.md  the queue: "- [ ] 2026-11-26 (6.2 · msg …): what, why"
//   topics/<slug>/visuals/index.json   generated by `visuals check`: steps, when it was last
//                                      rendered, what the checker measured, for which file contents
//
// The header (also read in the browser, for the note under the drawing):
//   /* visual
//   title: Budding and fusion: which side is which
//   skills: 3.4, 2.2
//   status: draft | ready | retired
//   shows: one line: what the learner sees
//   use: one line: the moment a tutor should reach for it
//   params: step=1..5 · upto=3 (stop there, ask what comes next) · hl=lumen
//   simplified: what the picture leaves out or distorts (shown under it; a cartoon says it is one)
//   sources: where the numbers and shapes come from
//   reviewed: set by `visuals ready`
//   */
// A visual is `ready` only through `bin/learn visuals ready`, which wants a fresh, clean render
// check of the file as it is now and a line saying who looked at what. docs/visuals.md has the reasons.
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const S = require('./store');

const NAME = /^[a-z0-9][a-z0-9-]*$/;
const KEYS = ['title', 'skills', 'status', 'kind', 'shows', 'use', 'params', 'simplified', 'sources', 'reviewed'];
const dir = slug => path.join(S.topicDir(slug), 'visuals');
const fileOf = (slug, name) => path.join(dir(slug), name + '.js');
const list0 = s => (s ? String(s).split(',').map(x => x.trim()).filter(Boolean) : []);

function parseHeader(src) {
  const m = String(src).match(/^\s*\/\*+\s*visual\b[^\n]*\n([\s\S]*?)\*\//), out = {};
  let k = null;
  for (const line of (m ? m[1] : '').split('\n')) {
    const kv = line.match(/^\s*([a-z][a-z-]*)\s*:\s*(.*)$/);
    if (kv) { k = kv[1]; out[k] = kv[2].trim(); } else if (k && line.trim()) out[k] += ' ' + line.trim();
  }
  return out;
}
// set (or add) one header line, keeping the rest of the file as it is
function setHeader(src, key, value) {
  const m = String(src).match(/^(\s*\/\*+\s*visual\b[^\n]*\n)([\s\S]*?)(\*\/)/);
  if (!m) return `/* visual\n${key}: ${value}\n*/\n${src}`;
  const lines = m[2].replace(/\n$/, '').split('\n');
  const i = lines.findIndex(l => new RegExp(`^\\s*${key}\\s*:`).test(l));
  if (i >= 0) { let j = i + 1; while (j < lines.length && lines[j].trim() && !/^\s*[a-z][a-z-]*\s*:/.test(lines[j])) j++; lines.splice(i, j - i, `${key}: ${value}`); }
  else lines.push(`${key}: ${value}`);
  return m[1] + lines.join('\n') + '\n' + m[3] + src.slice(m[0].length);
}
const readIndex = slug => { try { return S.readJSON(path.join(dir(slug), 'index.json'), {}) || {}; } catch { return {}; } };
const kitSrc = slug => S.readText(path.join(dir(slug), '_kit.js'), '');
// what a check is valid for: this file and this kit (a changed kit redraws every visual)
const hashOf = (slug, src) => crypto.createHash('sha1').update(src).update('\0').update(kitSrc(slug)).digest('hex').slice(0, 12);

function list(slug) {
  let files = [];
  try { files = fs.readdirSync(dir(slug)).filter(f => f.endsWith('.js') && NAME.test(f.slice(0, -3))).sort(); } catch {}
  const idx = readIndex(slug);
  return files.map(f => {
    const name = f.slice(0, -3), src = S.readText(path.join(dir(slug), f), ''), hd = parseHeader(src), ix = idx[name] || null;
    return { name, file: path.join(dir(slug), f), ...hd, status: ['ready', 'retired'].includes(hd.status) ? hd.status : 'draft', skills: list0(hd.skills),
      steps: ix?.steps || [], check: ix, fresh: !!ix && ix.hash === hashOf(slug, src) };
  });
}
const get = (slug, name) => list(slug).find(v => v.name === name) || null;

// GET /visuals/<slug>/<name>.js (and _kit.js) -> source, or null. Used by the server and by viz-check.
function serve(urlPath) {
  const m = String(urlPath).match(/^\/visuals\/([a-z0-9][a-z0-9-]*)\/(_kit|[a-z0-9][a-z0-9-]*)\.js$/);
  if (!m || !S.listTopics().includes(m[1])) return null;
  return S.readText(path.join(dir(m[1]), m[2] + '.js'), null);
}

// the one line a tutor pastes
const embed = (v, step) => `![caption](visual:${v.name}${step ? `?step=${step}` : ''})`;
const stepsLine = v => v.steps.map((s, i) => `${i + 1} ${s.title || s.id}`).join(' · ');
function describe(v, { full = false } = {}) {
  const out = [`  ${v.name}  [${v.skills.join(', ') || '-'}]${v.status === 'ready' ? '' : '  (' + v.status + (v.status === 'draft' ? ': not reviewed yet' : '') + ')'}  ${v.title || ''}`];
  // in lists one screen line each (resume prints several); `show` has it all
  const cut = t => (full || t.length <= 230 ? t : t.slice(0, 229).replace(/\s+\S*$/, '') + '…');
  if (v.shows) out.push(`      shows: ${cut(v.shows)}`);
  if (v.use) out.push(`      use:   ${cut(v.use)}`);
  if (v.steps.length) out.push(`      steps: ${stepsLine(v)}`);
  if (full) {
    if (v.params) out.push(`      params: ${v.params}`);
    if (v.simplified) out.push(`      simplified: ${v.simplified}`);
    if (v.sources) out.push(`      sources: ${v.sources}`);
    if (v.reviewed) out.push(`      reviewed: ${v.reviewed}`);
    out.push(`      check: ${!v.check ? 'never rendered (bin/learn visuals check ' + v.name + ')' : `${v.check.at.slice(0, 16).replace('T', ' ')}, ${v.check.problems} problem(s)${v.fresh ? '' : '; the file or the kit changed since: check again'}`}`);
    out.push(`      file: ${S.shown(v.file)}`);
  }
  out.push(`      ${embed(v)}${v.steps.length ? `   (a still: ?step=N · stop early and ask what comes next: ?upto=N)` : ''}`);
  return out.join('\n');
}

// words -> the visuals that match, best first (name, title, shows, use, skills, step titles)
function find(slug, query) {
  const words = String(query).toLowerCase().split(/[^a-z0-9.⁺⁻+]+/).filter(w => w.length > 1 || /\d/.test(w));
  return list(slug).filter(v => v.status !== 'retired').map(v => {
    const strong = `${v.name} ${v.title || ''} ${v.skills.join(' ')}`.toLowerCase(), weak = `${v.shows || ''} ${v.use || ''} ${stepsLine(v)} ${v.simplified || ''}`.toLowerCase();
    let score = 0; for (const w of words) score += strong.includes(w) ? 3 : weak.includes(w) ? 1 : 0;
    return { v, score };
  }).filter(x => x.score > 0).sort((a, b) => b.score - a.score || (a.v.status === 'ready' ? -1 : 1)).map(x => x.v);
}

// ---------- the queue: requests.md
const reqFile = slug => path.join(dir(slug), 'requests.md');
const REQ_HEAD = `# Visuals wanted\n\nWhat tutors wished they had mid-lesson (\`bin/learn visuals want "…" --skill id\`), for the visuals job\n(docs/jobs/visuals.md). Done: \`- [x] … → <name>\`. Declined: \`- [x] … → no: why\`.\n\n`;
function requests(slug) { return S.readText(reqFile(slug), '').split('\n').filter(l => /^- \[ \] /.test(l)); }
function want(slug, text, { skill, ref } = {}) {
  S.ensureDir(dir(slug));
  const cur = S.readText(reqFile(slug), null) ?? REQ_HEAD;
  const tag = [skill, ref ? 'msg ' + ref : null].filter(Boolean).join(' · ');
  const line = `- [ ] ${S.localDate()}${tag ? ` (${tag})` : ''}: ${String(text).replace(/\s+/g, ' ').trim()}`;
  fs.writeFileSync(reqFile(slug), cur.replace(/\n*$/, '\n') + line + '\n');
  return line;
}

// ---------- what a tutor sees in `resume`: the visuals for where the lesson is, each with its line
function near(slug, meta) {
  const ids = new Set();
  const add = id => { if (id) ids.add(String(id)); };
  add(meta.focus);
  // the focus's siblings and what builds on it next
  S.walkSkills(meta.skills || [], (s, parent) => { if (parent && (parent.children || []).some(c => String(c.id) === String(meta.focus))) add(s.id); if ((s.needs || []).map(String).includes(String(meta.focus))) add(s.id); });
  try { for (const n of S.readNotes(slug).items) if (n.status === 'open' && ['review', 'misconception'].includes(n.kind)) add(n.skill); } catch {}
  try { const J = S.readJournal(slug); for (const t of ['a', 'b', null]) for (const s of S.pendingQuestion(J, t)?.skills || []) add(s); } catch {}
  return ids;
}
function resumeSection(slug, meta) {
  const all = list(slug), ready = all.filter(v => v.status === 'ready');
  const style = (S.readText(path.join(dir(slug), 'STYLE.md'), '').match(/^## In short[^\n]*\n([\s\S]*?)(?=^## |(?![\s\S]))/m) || [])[1];
  if (!all.length && !style) return null;
  const ids = near(slug, meta), hit = ready.filter(v => v.skills.some(s => ids.has(s))), rest = ready.filter(v => !hit.includes(v));
  const out = [];
  if (hit.length) out.push('For the focus, what comes next and the open reviews:', ...hit.map(v => describe(v)));
  if (rest.length) out.push(`Others (\`bin/learn visuals show <name>\`): ${rest.map(v => `${v.name} [${v.skills.join(',')}]`).join(', ')}`);
  if (!ready.length) out.push('(none ready yet)');
  const drafts = all.filter(v => v.status === 'draft').length, reqs = requests(slug).length;
  out.push(`Find one: \`bin/learn visuals find <words>\`. Wished you had one? \`bin/learn visuals want "an animation of X, because Y" --skill <id>\` (one line; the visuals job builds it while the learner is away${reqs || drafts ? `; ${reqs} wanted, ${drafts} in draft` : ''}).`);
  if (style && style.trim()) out.push('', 'How things are drawn in this topic (visuals/STYLE.md; your own `viz js` drawings follow it too):', style.trim());
  return out.join('\n');
}
// for the planner: what there is, what is asked for, where the lesson is going without one
function snapshotLine(slug, meta) {
  const all = list(slug), reqs = requests(slug);
  if (!all.length && !reqs.length && !fs.existsSync(dir(slug))) return null;
  const ids = near(slug, meta), have = new Set(all.filter(v => v.status !== 'retired').flatMap(v => v.skills));
  const without = [...ids].filter(i => !have.has(i));
  const stale = all.filter(v => v.status === 'ready' && !v.fresh).map(v => v.name);
  return `- visuals: ${all.filter(v => v.status === 'ready').length} ready, ${all.filter(v => v.status === 'draft').length} draft, ${reqs.length} wanted by tutors${without.length ? `; focus, next and review skills without one: ${without.join(', ')}` : ''}${stale.length ? `; changed since their check: ${stale.join(', ')}` : ''}`;
}

// ---------- check: render every step headless, measure, save PNGs to look at
async function check(slug, name, { width, mid = false, extra = [], live = 0 } = {}) {
  const v = get(slug, name);
  if (!v) throw new Error(`no visual ${name} in ${slug} (${S.shown(dir(slug))}/)`);
  const VC = require('./vizcheck');
  const outDir = path.join(S.STATE, 'viz-check', `visual-${slug}-${name}`);
  // pass 1: draw it as embedded with no parameters, to learn its steps
  const first = await VC.check({ text: `![](visual:${name})\n`, topic: slug, label: `visual-${slug}-${name}`, outDir, width });
  const steps = (first.scenes || []).find(s => s.name === name)?.steps || [];
  const frames = [{ q: '', label: 'as embedded with no parameters (the first thing the learner sees)' }];
  steps.forEach((s, i) => { if (mid) frames.push({ q: `?t=${i + 0.5}`, label: `half-way through step ${i + 1}` }); frames.push({ q: `?step=${i + 1}`, label: `step ${i + 1}: ${s.title || s.id}` }); });
  for (const q of extra) frames.push({ q: '?' + String(q).replace(/^\?/, ''), label: 'with ' + q });
  let r = first;
  if (frames.length > 1) r = await VC.check({ text: frames.map(f => `![](visual:${name}${f.q})\n`).join('\n'), topic: slug, label: `visual-${slug}-${name}`, outDir, width });
  // --live N: let it really run for N seconds (Play all pressed), to catch what a still can't: an error
  // in the middle of the motion, things drifting over each other. One more frame, dark theme.
  let liveRun = null;
  if (live) {
    liveRun = await VC.check({ text: `![](visual:${name}?${extra[0] ? String(extra[0]).replace(/^\?/, '') + '&' : ''}play=1)\n`, topic: slug, label: `visual-${slug}-${name}-live`, outDir: outDir + '-live', width, live });
  }
  const src = S.readText(v.file, '');
  const problems = (liveRun ? liveRun.errors.length + liveRun.drawings.reduce((n, d) => n + d.problems.length, 0) : 0) + r.drawings.reduce((n, d) => n + d.problems.length, 0) + r.errors.length;
  const idx = readIndex(slug);
  idx[name] = { hash: hashOf(slug, src), at: new Date().toISOString(), width: r.width, steps, frames: frames.length, problems };
  S.writeJSON(path.join(dir(slug), 'index.json'), Object.fromEntries(Object.entries(idx).filter(([k]) => fs.existsSync(fileOf(slug, k))).sort()));
  return { v, r, frames, steps, problems, liveRun, live };
}
function checkReport({ v, r, frames, steps, problems, liveRun, live }) {
  const LABEL = { error: 'error box', empty: 'empty', wide: 'too wide', tiny: 'tiny text', cut: 'text cut off', covered: 'hidden text', faint: 'unreadable text', overlap: 'overlapping text' };
  const out = [`visuals check ${v.name}: ${steps.length} step(s), ${frames.length} frame(s), light and dark, ${r.width}px wide: ${problems ? problems + ' problem(s)' : 'nothing measurable is wrong'}`];
  for (const e of r.errors) out.push(`  ✗ JS error (${e.themes.join(', ')}): ${String(e.text).split('\n')[0]}`);
  r.drawings.forEach((d, i) => {
    out.push(`#${d.n} ${frames[i]?.label || ''}: ${d.problems.length ? d.problems.length + ' problem(s)' : 'ok'}`);
    for (const p of d.problems.slice(0, 6)) out.push(`  ✗ ${LABEL[p.kind] || p.kind}: ${p.text}${p.themes.length < 2 ? ` (${p.themes[0]} theme only)` : ''}`);
    if (d.problems.length > 6) out.push(`  ✗ … and ${d.problems.length - 6} more`);
    for (const n of d.notes) if (!/^interactive/.test(n)) out.push(`  · ${n}`);
    if (Object.keys(d.png).length) out.push(`  look: ${Object.values(d.png).map(S.shown).join('  ')}`);
  });
  if (liveRun) {
    const d = liveRun.drawings[0];
    out.push(`live, after running ${live} s: ${liveRun.errors.length || d?.problems.length ? '' : 'no errors, nothing measurable is wrong'}`);
    for (const e of liveRun.errors) out.push(`  ✗ JS error while running: ${String(e.text).split('\n')[0]}`);
    for (const p of (d?.problems || []).slice(0, 6)) out.push(`  ✗ ${LABEL[p.kind] || p.kind}: ${p.text}`);
    if (d?.png.dark) out.push(`  look: ${S.shown(d.png.dark)}`);
  }
  out.push(`all frames on one sheet: ${S.shown(path.join(r.dir, 'message-dark.png'))}  ${S.shown(path.join(r.dir, 'message-light.png'))}`);
  out.push('Now look at the PNGs (Read shows them). The machine measured the text; only eyes can tell whether each step shows what its caption says, things that should touch do, and nothing teaches the wrong thing.');
  if (!problems && v.status !== 'ready') out.push(`When it has been looked at and its science checked: bin/learn visuals ready ${v.name} --reviewed "who checked what"`);
  return out.join('\n');
}
function ready(slug, name, { reviewed, despite } = {}) {
  const v = get(slug, name);
  if (!v) throw new Error(`no visual ${name} in ${slug}`);
  if (!reviewed) throw new Error('say who looked at what: --reviewed "frames looked at in both themes; science checked against … by a second agent"');
  for (const k of ['title', 'skills', 'shows', 'use', 'simplified']) if (!v[k] || (Array.isArray(v[k]) && !v[k].length)) throw new Error(`${name}: the header has no "${k}:" line (tutors find and judge a visual by it${k === 'simplified' ? '; it is shown under the drawing, so a cartoon says it is one' : ''})`);
  if (!v.check || !v.fresh) throw new Error(`${name} ${v.check ? 'changed since it was last rendered' : 'was never rendered'}: run \`bin/learn visuals check ${name}\` and look at the frames first`);
  if (v.check.problems && !despite) throw new Error(`the last check of ${name} found ${v.check.problems} problem(s). Fix them, or if they are false alarms: --despite "why they are fine"`);
  let src = S.readText(v.file, '');
  src = setHeader(src, 'status', 'ready');
  src = setHeader(src, 'reviewed', `${S.localDate()} ${String(reviewed).replace(/\s+/g, ' ').trim()}${despite ? ` (checker flags accepted: ${String(despite).replace(/\s+/g, ' ').trim()})` : ''}`);
  fs.writeFileSync(v.file, src);
  // the header is part of the file: keep the check valid for the new contents
  const idx = readIndex(slug); idx[name] = { ...idx[name], hash: hashOf(slug, src) }; S.writeJSON(path.join(dir(slug), 'index.json'), idx);
  return get(slug, name);
}

// bin/learn visuals [t] [list | find <words> | show <name> | want "…" | wanted | check <name>|--all | ready <name>]
async function cli(f, topicOf, die) {
  const slug = topicOf(f);
  const sub = f._.shift() || 'list';
  const all = list(slug);
  if (sub === 'list') {
    if (!all.length) console.log(`${slug}: no prepared visuals yet (docs/visuals.md; ask for one: bin/learn visuals want "…" --skill id)`);
    else {
      const n = s => all.filter(v => v.status === s).length;
      console.log(`${slug}: ${all.length} prepared visual(s): ${n('ready')} ready, ${n('draft')} draft${n('retired') ? `, ${n('retired')} retired` : ''}. Embed one on its own line: ![your caption](visual:<name>)`);
      for (const v of all.filter(v => v.status !== 'retired')) console.log(describe(v));
    }
    const reqs = requests(slug);
    if (reqs.length) console.log(`\nWanted (${S.shown(reqFile(slug))}):\n${reqs.map(l => '  ' + l).join('\n')}`);
  } else if (sub === 'find') {
    const q = f._.join(' ');
    if (!q) die('usage: visuals [t] find <words>');
    const hits = find(slug, q);
    console.log(hits.length ? hits.map(v => describe(v)).join('\n') : `no visual matches "${q}" in ${slug}. Ask for one: bin/learn visuals want "…" --skill id`);
  } else if (sub === 'show') {
    const v = get(slug, f._[0] || '');
    if (!v) die(`no visual ${f._[0] || ''} in ${slug} (have: ${all.map(x => x.name).join(', ') || 'none'})`);
    console.log(describe(v, { full: true }));
  } else if (sub === 'want') {
    const text = f._.join(' ').trim();
    if (!text) die('usage: visuals [t] want "what it should show, and what the learner got wrong without it" [--skill id] [--ref msg-id]');
    console.log(`queued for the visuals job: ${want(slug, text, { skill: f.skill, ref: f.ref })}`);
  } else if (sub === 'wanted') {
    const reqs = requests(slug);
    console.log(reqs.length ? reqs.join('\n') : '(nothing wanted)');
  } else if (sub === 'check') {
    const names = f.all ? all.filter(v => v.status !== 'retired').map(v => v.name) : f._;
    if (!names.length) die('usage: visuals [t] check <name>… | --all  [--mid] [--live seconds] [--width 900] [--with "step=2&hl=x"]');
    let bad = 0;
    for (const name of names) {
      const res = await check(slug, name, { width: Math.max(320, Math.min(2400, Number(f.width) || 900)), mid: !!f.mid, extra: f.with ? [f.with] : [], live: Math.max(0, Math.min(60, Number(f.live) || 0)) });
      console.log(checkReport(res) + (names.length > 1 ? '\n' : ''));
      if (res.problems) bad++;
    }
    if (bad) process.exitCode = 1;
  } else if (sub === 'ready') {
    const name = f._[0];
    if (!name) die('usage: visuals [t] ready <name> --reviewed "who checked what" [--despite "why the checker\'s flags are fine"]');
    try { const v = ready(slug, name, { reviewed: f.reviewed, despite: f.despite }); console.log(`${v.name} is ready: tutors now see it in resume for skills ${v.skills.join(', ')}.\n${describe(v)}`); }
    catch (e) { die(e.message); }
  } else die(`unknown: visuals ${sub}\nusage: visuals [t] [list | find <words> | show <name> | want "…" [--skill id] [--ref msg] | wanted | check <name>|--all [--mid] | ready <name> --reviewed "…"]`);
}

module.exports = { NAME, dir, list, get, serve, find, want, requests, check, checkReport, ready, resumeSection, snapshotLine, parseHeader, setHeader, cli };
